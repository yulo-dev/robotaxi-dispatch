// Command sim runs the offline fleet simulator and compares dispatch strategies.
//
//	go run ./cmd/sim -vehicles 80 -rate 150 -peak 3 -minutes 120 -seeds 5 -batch 2s -json out.json
package main

import (
	"bytes"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"runtime"
	"strconv"
	"strings"
	"time"

	"github.com/yulo-dev/robotaxi-dispatch/internal/geo"
	"github.com/yulo-dev/robotaxi-dispatch/internal/sim"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "sim:", err)
		os.Exit(1)
	}
}

func run() error {
	cfg := sim.DefaultConfig()
	vehicles := flag.Int("vehicles", cfg.Vehicles, "fleet size")
	rate := flag.Float64("rate", cfg.RatePerHour, "off-peak ride requests per hour")
	peak := flag.Float64("peak", cfg.PeakMult, "demand multiplier during the middle third of the run")
	minutes := flag.Int("minutes", cfg.DurationSec/60, "minutes of demand to generate")
	seeds := flag.Int("seeds", 5, "number of seeds (1..N)")
	batch := flag.Duration("batch", time.Duration(cfg.BatchSec)*time.Second, "batch window (whole seconds)")
	accept := flag.Float64("accept", cfg.AcceptProb, "probability a vehicle accepts a dispatch")
	strategies := flag.String("strategies", "", "comma-separated strategies (default: all four)")
	jsonOut := flag.String("json", "", "write full results as JSON to this file")
	sweep := flag.String("sweep", "", "comma-separated fleet sizes to sweep, e.g. 40,60,80,100,120")
	resultsMD := flag.String("results", "", "write Markdown report to this file")
	goBench := flag.String("gobench", "", "include `go test -bench` output from this file in the report")
	parallel := flag.Int("parallel", runtime.NumCPU(), "concurrent runs")
	flag.Parse()

	cfg.Vehicles = *vehicles
	cfg.RatePerHour = *rate
	cfg.PeakMult = *peak
	cfg.DurationSec = *minutes * 60
	cfg.AcceptProb = *accept
	if *batch < time.Second || *batch%time.Second != 0 {
		return fmt.Errorf("batch must be a whole number of seconds >= 1s")
	}
	cfg.BatchSec = int(*batch / time.Second)
	if err := cfg.Validate(); err != nil {
		return err
	}
	sts := sim.Strategies
	if *strategies != "" {
		sts = nil
		for _, name := range strings.Split(*strategies, ",") {
			st, ok := sim.StrategyByName(strings.TrimSpace(name))
			if !ok {
				return fmt.Errorf("unknown strategy %q", name)
			}
			sts = append(sts, st)
		}
	}

	net, err := geo.NewGrid(cfg.Grid)
	if err != nil {
		return err
	}
	seedList := sim.SeedList(*seeds)

	start := time.Now()
	exp := sim.RunExperiment(net, cfg, seedList, sts, *parallel)
	fmt.Printf("vehicles=%d rate=%.0f/h peak=x%.1f minutes=%d batch=%ds seeds=%d (mean ± std)\n",
		cfg.Vehicles, cfg.RatePerHour, cfg.PeakMult, *minutes, cfg.BatchSec, *seeds)
	sim.WriteText(os.Stdout, exp)

	var points []sim.SweepPoint
	if *sweep != "" {
		for _, s := range strings.Split(*sweep, ",") {
			v, err := strconv.Atoi(strings.TrimSpace(s))
			if err != nil || v <= 0 {
				return fmt.Errorf("bad sweep value %q", s)
			}
			c := cfg
			c.Vehicles = v
			e := sim.RunExperiment(net, c, seedList, sts, *parallel)
			points = append(points, sim.SweepPoint{Vehicles: v, Experiment: e})
			fmt.Printf("\nsweep vehicles=%d\n", v)
			sim.WriteText(os.Stdout, e)
		}
	}
	elapsed := time.Since(start)

	if *jsonOut != "" {
		out := struct {
			Config sim.Config       `json:"config"`
			Main   sim.Experiment   `json:"main"`
			Sweep  []sim.SweepPoint `json:"sweep,omitempty"`
		}{cfg, exp, points}
		b, err := json.MarshalIndent(out, "", "  ")
		if err != nil {
			return err
		}
		if err := os.WriteFile(*jsonOut, b, 0o644); err != nil {
			return err
		}
	}
	if *resultsMD != "" {
		var buf bytes.Buffer
		cmd := "go run ./cmd/sim " + strings.Join(os.Args[1:], " ")
		if err := writeReport(&buf, cmd, cfg, net, exp, points, *goBench, *parallel, elapsed); err != nil {
			return err
		}
		if err := os.WriteFile(*resultsMD, buf.Bytes(), 0o644); err != nil {
			return err
		}
	}
	return nil
}

func writeReport(buf *bytes.Buffer, cmd string, cfg sim.Config, net *geo.Network, exp sim.Experiment,
	points []sim.SweepPoint, goBench string, parallel int, elapsed time.Duration) error {
	rows, cols := net.Dims()
	fmt.Fprintln(buf, "# Results")
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, "This file is generated by `make bench`. Do not edit it by hand.")
	fmt.Fprintln(buf)
	fmt.Fprintf(buf, "- Generated: %s\n", time.Now().UTC().Format("2006-01-02 15:04 MST"))
	fmt.Fprintf(buf, "- Machine: %s, %d CPUs, %s %s/%s\n", cpuModel(), runtime.NumCPU(), runtime.Version(), runtime.GOOS, runtime.GOARCH)
	fmt.Fprintf(buf, "- Command: `%s`\n", cmd)
	fmt.Fprintf(buf, "- Simulation wall time: %.1f s with %d concurrent runs\n", elapsed.Seconds(), parallel)
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, "## Setup")
	fmt.Fprintln(buf)
	fmt.Fprintf(buf, "- Road network: %d x %d grid (%d nodes, %d in the main component), %.0f m spacing, speed classes %v km/h, %.0f%% of edges closed, network seed %d\n",
		rows, cols, net.NumNodes(), len(net.MainNodes()), cfg.Grid.SpacingM, cfg.Grid.SpeedsKmh, cfg.Grid.BlockedFrac*100, cfg.Grid.Seed)
	fmt.Fprintf(buf, "- Demand: %.0f requests/h off-peak, x%.1f during the middle third, %d minutes, 3 to 5 hotspots, trips 1 to 5 km straight-line\n",
		cfg.RatePerHour, cfg.PeakMult, cfg.DurationSec/60)
	fmt.Fprintf(buf, "- Dispatch: %d s batch window, candidates within %.0f m (then %.0f m), top %d, accept probability %.2f, ride fails after %d s unassigned\n",
		cfg.BatchSec, cfg.RadiusM, cfg.ExpandM, cfg.TopK, cfg.AcceptProb, cfg.MatchTimeout)
	fmt.Fprintf(buf, "- Straight-line strategies convert distance to ETA at %.0f km/h; vehicles always move along A* routes\n", cfg.StraightKmh)
	fmt.Fprintf(buf, "- Each seed generates demand and fleet positions once; all strategies run on the same scenario. Values are mean ± sample std over %d seeds.\n", len(exp.Seeds))
	fmt.Fprintln(buf)
	fmt.Fprintln(buf, "Not modeled: traffic or time-varying speeds, decision latency (accept/reject is instant), rider cancellations,")
	fmt.Fprintln(buf, "idle-vehicle repositioning, battery and charging, and positions between nodes (a vehicle appears at its")
	fmt.Fprintln(buf, "destination when the route time elapses). The road network is a synthetic grid, not a real street map.")
	fmt.Fprintln(buf)
	fmt.Fprintf(buf, "## Strategy comparison (%d vehicles)\n\n", cfg.Vehicles)
	sim.WriteMainTable(buf, exp)
	if len(points) > 0 {
		fmt.Fprintln(buf)
		fmt.Fprintln(buf, "## Fleet size sweep")
		fmt.Fprintln(buf)
		fmt.Fprintln(buf, "Same demand and dispatch settings; only the fleet size changes.")
		fmt.Fprintln(buf)
		sim.WriteSweepTable(buf, points)
	}
	if goBench != "" {
		f, err := os.Open(goBench)
		if err != nil {
			return err
		}
		defer func() { _ = f.Close() }()
		fmt.Fprintln(buf)
		fmt.Fprintln(buf, "## Microbenchmarks")
		fmt.Fprintln(buf)
		fmt.Fprintln(buf, "From `go test -bench` on the same machine. A*/Dijkstra rows are single routes on the default grid; Hungarian/Greedy rows are random dense n x n matrices.")
		fmt.Fprintln(buf)
		if err := sim.WriteGoBenchTable(buf, f); err != nil {
			return err
		}
	}
	return nil
}

func cpuModel() string {
	b, err := os.ReadFile("/proc/cpuinfo")
	if err != nil {
		return runtime.GOARCH
	}
	for _, line := range strings.Split(string(b), "\n") {
		if strings.HasPrefix(line, "model name") {
			if i := strings.Index(line, ":"); i >= 0 {
				return strings.TrimSpace(line[i+1:])
			}
		}
	}
	return runtime.GOARCH
}
