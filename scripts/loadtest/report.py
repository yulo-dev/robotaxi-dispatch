#!/usr/bin/env python3
"""Render docs/loadtest.md from the files written by run.sh."""
import json
import os
import sys

out = sys.argv[1]
summary = json.load(open(os.path.join(out, "summary.json")))["metrics"]
machine = open(os.path.join(out, "machine.txt")).read().strip().splitlines()
invariants = open(os.path.join(out, "invariants.txt")).read().rstrip()
server = {}
path = os.path.join(out, "server_metrics.txt")
if os.path.exists(path):
    for line in open(path):
        name, value = line.split()
        server[name] = float(value)

def count(name):
    return summary.get(name, {}).get("count", 0)

endpoints = [
    "POST /v1/rides",
    "POST /v1/vehicles/{id}/heartbeat",
    "POST /v1/dispatch/{ride_id}/decision",
    "POST /v1/rides/{id}/pickup",
    "POST /v1/rides/{id}/complete",
]

print("# Load test results")
print()
print("Generated by `make loadtest` (`scripts/loadtest/run.sh`). Do not edit by hand.")
print()
print("## Setup")
print()
for line in machine:
    k, _, v = line.partition(": ")
    print(f"- {k}: {v}")
print("- API, Postgres, Redis, and k6 ran on the same machine, so they compete for the same CPUs.")
print("- Scenario: 200 vehicles heartbeating every 2 s; ride requests ramp from 10 to 100 per second over 3 minutes;")
print("  5% of ride requests resend a previous Idempotency-Key with the same body; vehicles accept 90% of offers and")
print("  call pickup and complete on their next two heartbeats.")
print()
print("## Throughput and errors")
print()
reqs = summary["http_reqs"]
failed = summary["http_req_failed"]
print("| metric | value |")
print("|---|---|")
duration = reqs["count"] / reqs["rate"] if reqs["rate"] else 0
trips = summary.get("trips_completed", {})
print(f"| run length, including the 10 s warm-up (s) | {duration:.0f} |")
print(f"| HTTP requests | {reqs['count']} ({reqs['rate']:.1f}/s) |")
print(f"| HTTP error rate (status not 2xx) | {100 * failed['value']:.2f}% |")
print(f"| unique ride requests | {count('ride_requests_unique')} |")
print(f"| idempotent resends | {count('ride_requests_replayed')} |")
print(f"| resends that did not return the original ride | {count('ride_replay_mismatch')} |")
print(f"| vehicle decisions | {count('vehicle_decisions')} |")
print(f"| trips completed | {count('trips_completed')} ({trips.get('rate', 0):.1f}/s averaged over the run) |")
print()
print("## Latency per endpoint (ms)")
print()
print("| endpoint | avg | p50 | p95 | p99 | max |")
print("|---|---|---|---|---|---|")
for e in endpoints:
    m = summary.get("http_req_duration{name:%s}" % e)
    if not m:
        continue
    print(f"| {e} | {m['avg']:.1f} | {m['p(50)']:.1f} | {m['p(95)']:.1f} | {m['p(99)']:.1f} | {m['max']:.1f} |")
if server:
    print()
    print("## Server counters at the end of the run")
    print()
    print("| counter | value |")
    print("|---|---|")
    for name in sorted(server):
        print(f"| {name} | {server[name]:.0f} |")
print()
print("## Invariant checks (`scripts/loadtest/check_invariants.sql`)")
print()
print("Run 20 s after k6 finished; the ride status counts include rides the sweeper failed in that time.")
print()
print("```")
print(invariants)
print("```")
